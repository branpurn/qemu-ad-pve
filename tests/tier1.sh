chk "C4d CRLF list entry does not match (falls back to vendor, safe)" '[[ $o == REAL* ]]'
printf '200\n' > "$T/vms"; command rm -f "$W/side.bak"; mv "$W/side" "$W/side.bak"
K -pidfile /var/run/qemu-server/200.pid >/dev/null 2>&1; rc=$?; mv "$W/side.bak" "$W/side"
chk "C4e listed + missing side binary: loud failure (rc!=0), unlisted unaffected" '[[ $rc -ne 0 && $(K -pidfile /var/run/qemu-server/201.pid) == REAL* ]]'

echo "== C5 --purge guard (rm is a no-op recorder)"
purge() { fresh; PATH="$W/stub:$PATH" bash -c "source '$W/lib.sh'; set -euo pipefail; rm(){ echo \"RM \$*\" >> '$T/rm.log'; }
   PREFIX='$1' LIST_FILE='$T/vms' WRAPPER_PATH='$T/n1' VENDOR_PATH='$T/n2'; uninstall --purge" >/dev/null 2>&1; echo $?; }
for p in / /usr /etc /opt /opt/ /usr/local /usr/local/ /srv /home/x relative/opt opt/x; do
  r=$(purge "$p"); chk "C5 reject PREFIX='$p' (rc!=0, nothing removed)" '[[ $r -ne 0 && ! -s $T/rm.log ]]'
done
for p in /opt/qemu-ad /usr/local/qemu-ad /srv/qad; do
  r=$(purge "$p"); chk "C5 allow PREFIX='$p'" '[[ $r -eq 0 && -s $T/rm.log ]]'
done
for p in /opt/../usr /opt/qemu-ad/../.. /usr/local/bin /usr/local/../../etc; do
  r=$(purge "$p"); if [[ $r -ne 0 && ! -s $T/rm.log ]]; then ok "C5 reject traversal/system dir PREFIX='$p'"; else bad "C5 GUARD BYPASS PREFIX='$p' would rm: $(cat "$T/rm.log" 2>/dev/null | head -1)"; fi
done
fresh; L 'install_wrapper' >/dev/null 2>&1; r=$(PREFIX=/usr L 'uninstall --purge' >/dev/null 2>&1; echo $?)
chk "C5x refused purge changes nothing (divert + wrapper still in place)" '[[ $r -ne 0 ]] && grep -q "Generated by qemu-ad-pve" "$T/kvm" && [[ -e $T/kvm.pve ]]'
fresh; PATH="$W/stub:$PATH" bash -c "source '$W/lib.sh'; set -euo pipefail; rm(){ echo \"RM \$*\" >> '$T/rm.log'; }; PREFIX= LIST_FILE='$T/vms' WRAPPER_PATH='$T/n1' VENDOR_PATH='$T/n2'; echo PREFIX=\$PREFIX >> '$T/rm.log'; uninstall --purge" >/dev/null 2>&1
note "C5 empty PREFIX= env var: $(head -2 "$T/rm.log" 2>/dev/null | tr '\n' ' ')"

echo "== C6 +pveN strip only on -machine/-M"
mkw; printf '200\n' > "$T/vms"; P='-pidfile /var/run/qemu-server/200.pid'
o=$(K -machine 'type=pc-q35-10.1+pve1,accel=kvm' $P); chk "C6a -machine type=...+pve1 stripped" '[[ $o == *"[type=pc-q35-10.1,accel=kvm]"* ]]'
o=$(K -machine pc-q35-10.1+pve12 $P);               chk "C6b -machine bare +pve12 stripped"       '[[ $o == *"[pc-q35-10.1]"* ]]'
o=$(K -M pc-q35-10.1+pve2 $P);                      chk "C6c -M stripped"                          '[[ $o == *"[pc-q35-10.1]"* ]]'
o=$(K -name 'x+pve5' -smbios 'type=1,product=a+pve7' -drive 'file=/m/a+pve1/d' $P)
chk "C6d +pve in name/smbios/path untouched" '[[ $o == *"[x+pve5]"* && $o == *"product=a+pve7"* && $o == *"/m/a+pve1/d"* ]]'
o=$(K -machine pc-q35-10.1+pve1 -machine 'type=pc-i440fx-9.0+pve3' $P); chk "C6e two -machine args both stripped" '[[ $o == *"[pc-q35-10.1]"* && $o == *"[type=pc-i440fx-9.0]"* ]]'
o=$(K -name -machine pc-q35-10.1+pve1 $P);          note "C6f edge: '-name -machine X+pve1' (value that looks like option): $o"

echo "== C7 (simulated) vendor upgrade"
fresh; L 'install_wrapper' >/dev/null 2>&1; printf 'vendor-NEW\n' > "$T/kvm.pve"   # what dpkg does: new vendor lands on kvm.pve
grep -q "Generated by qemu-ad-pve" "$T/kvm" && ok "C7a wrapper untouched by new vendor file" || bad "C7a"
