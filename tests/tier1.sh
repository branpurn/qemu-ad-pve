#!/bin/bash
# Tier-1 harness for qemu-ad-pve.sh. Stubs only: no root, no dpkg, no PVE, no VM.
# Usage: qemu-ad-pve-tier1.sh /path/to/qemu-ad-pve.sh
# Everything happens in a mktemp dir. rm is shadowed by a no-op function for purge tests.
set -u
SCRIPT=$(readlink -f "${1:?path to qemu-ad-pve.sh}")
W=$(mktemp -d /tmp/qad-t1.XXXXXX); trap 'command rm -rf "$W"' EXIT
pass=0; fail=0; info=0
ok()   { printf 'PASS  %s\n' "$1"; pass=$((pass+1)); }
bad()  { printf 'FAIL  %s\n' "$1"; fail=$((fail+1)); }
note() { printf 'INFO  %s\n' "$1"; info=$((info+1)); }
chk()  { if eval "$2"; then ok "$1"; else bad "$1"; fi; }

# library = script minus the final "main" call
grep -q '^main "\$@"$' "$SCRIPT" || { echo "unexpected script tail"; exit 2; }
sed '$d' "$SCRIPT" > "$W/lib.sh"

# stub dpkg-divert modelled on the real one: --rename refuses to overwrite.
mkdir -p "$W/stub"
cat > "$W/stub/dpkg-divert" <<'S'
#!/bin/bash
st=$STATE/div; mode=list; ren=0; div=""; args=("$@"); path="${args[-1]}"
for ((i=0;i<${#args[@]}-1;i++)); do case ${args[i]} in
  --list) mode=list;; --remove) mode=remove;; --rename) ren=1;; --local) ;;
  --divert) div=${args[i+1]};; esac; done
[[ $* == *--list* ]] && mode=list || { [[ $mode == list ]] && mode=add; }
echo "$*" >> "$STATE/calls"
case $mode in
 list) [[ -f $st ]] && grep -F -- "$path" "$st" | awk -F'|' '{print "local diversion of "$1" to "$2}';;
 add) [[ -e $div ]] && { echo "dpkg-divert: error: rename involves overwriting" >&2; exit 2; }
      ((ren)) && mv "$path" "$div"; echo "$path|$div" > "$st";;
 remove) [[ -n ${FAIL_REMOVE:-} ]] && { echo "dpkg: error: dpkg frontend lock held" >&2; exit 2; }
      d=$(cut -d'|' -f2 "$st"); [[ -e $path ]] && { echo "dpkg-divert: error: rename involves overwriting $path" >&2; exit 2; }
      ((ren)) && mv "$d" "$path"; rm -f "$st";;
esac
S
chmod +x "$W/stub/dpkg-divert"
cat > "$W/real" <<'S'
#!/bin/bash
printf 'REAL'; printf ' [%s]' "$@"; echo
S
cat > "$W/side" <<'S'
#!/bin/bash
printf 'SIDE'; printf ' [%s]' "$@"; echo
S
chmod +x "$W/real" "$W/side"

# fresh scratch "host": /usr/bin/kvm == vendor
fresh() { T=$W/h; command rm -rf "$T"; mkdir -p "$T"; export STATE=$T; printf 'vendor\n' > "$T/kvm"; chmod +x "$T/kvm"; : > "$T/calls"; }
L() { # run snippet with lib sourced + paths set, strict mode like the real script
  PATH="$W/stub:$PATH" bash -c "source '$W/lib.sh'; set -euo pipefail
    WRAPPER_PATH='$T/kvm' VENDOR_PATH='$T/kvm.pve' SIDE_BIN='$W/side' LIST_FILE='$T/vms' LOG_FILE='$T/log' PREFIX=\${PREFIX:-/opt/qemu-ad}
    $1"; }
kvm_intact() { [[ -f $T/kvm ]] && [[ -x $T/kvm ]]; }

echo "== C1 install atomicity"
fresh; L 'write_wrapper(){ echo "injected write failure" >&2; return 1; }; install_wrapper' >/dev/null 2>&1; rc=$?
chk "C1a injected write failure: rc!=0"                    '[[ $rc -ne 0 ]]'
chk "C1a /usr/bin/kvm still the vendor file"               'kvm_intact && grep -qx vendor "$T/kvm"'
chk "C1a no divert was created"                            '! grep -q -- --rename "$T/calls"'
fresh; ln -s /dev/full "$T/kvm.qemu-ad-new"; L 'install_wrapper' >/dev/null 2>&1; rc=$?   # ENOSPC on staged file
chk "C1b ENOSPC on staged wrapper: rc!=0 and kvm intact"   '[[ $rc -ne 0 ]] && kvm_intact && grep -qx vendor "$T/kvm" && ! grep -q -- --rename "$T/calls"'
fresh; L 'write_wrapper(){ printf "if then\n" > "$1"; }; install_wrapper' >/dev/null 2>&1; rc=$?
chk "C1c wrapper failing bash -n: rc!=0, kvm intact, no divert" '[[ $rc -ne 0 ]] && kvm_intact && grep -qx vendor "$T/kvm" && ! grep -q -- --rename "$T/calls"'
fresh; L 'install_wrapper' >/dev/null 2>&1
chk "C1d good install: kvm is wrapper, kvm.pve is vendor"  'grep -q "Generated by qemu-ad-pve" "$T/kvm" && grep -qx vendor "$T/kvm.pve"'
cp "$T/kvm" "$W/w1"; L 'install_wrapper' >/dev/null 2>&1
chk "C1e reinstall idempotent (wrapper identical, vendor untouched)" 'cmp -s "$T/kvm" "$W/w1" && grep -qx vendor "$T/kvm.pve" && [[ $(grep -c -- --rename "$T/calls") -eq 1 ]]'
chk "C1f no staged leftovers after good install"            '[[ ! -e $T/kvm.qemu-ad-new ]]'
fresh; L 'install_wrapper' >/dev/null 2>&1; fresh2=1
fresh; PATH="$W/stub:$PATH" bash -c "source '$W/lib.sh'; set -euo pipefail; WRAPPER_PATH='$T/kvm' VENDOR_PATH='$T/kvm.pve' SIDE_BIN='$W/side' LIST_FILE='$T/vms' LOG_FILE='$T/log'
   mv(){ if [[ \${*: -1} == '$T/kvm' ]]; then return 1; fi; command mv \"\$@\"; }; install_wrapper" >/dev/null 2>&1
if [[ -e $T/kvm ]]; then ok "C1g (info) failed final mv: kvm present"; else note "C1g KNOWN RESIDUAL GAP: final mv fails after divert -> /usr/bin/kvm missing (no rollback)"; fi
fresh; L 'write_wrapper(){ return 1; }; install_wrapper' >/dev/null 2>&1; [[ -e $T/kvm.qemu-ad-new ]] && note "C1h staged file left behind after abort (cosmetic)" || ok "C1h no staged leftover after abort"

echo "== C2 uninstall order / dpkg failure"
fresh; L 'install_wrapper' >/dev/null 2>&1
FAIL_REMOVE=1 L 'uninstall' >/dev/null 2>&1; rc=$?
chk "C2a divert-remove failure: rc!=0"                      '[[ $rc -ne 0 ]]'
chk "C2a kvm still present AND is the wrapper"              'kvm_intact && grep -q "Generated by qemu-ad-pve" "$T/kvm"'
chk "C2a kvm.pve still present (divert untouched)"          '[[ -e $T/kvm.pve ]]'
chk "C2a no .qemu-ad-removed leftover"                      '[[ ! -e $T/kvm.qemu-ad-removed ]]'
L 'uninstall' >/dev/null 2>&1; rc=$?
chk "C2b clean uninstall: rc==0, kvm is vendor again"       '[[ $rc -eq 0 ]] && grep -qx vendor "$T/kvm" && [[ ! -e $T/kvm.pve ]] && [[ ! -e $T/kvm.qemu-ad-removed ]]'
L 'uninstall' >/dev/null 2>&1; rc=$?
chk "C2c uninstall twice: rc==0, kvm still vendor"          '[[ $rc -eq 0 ]] && grep -qx vendor "$T/kvm"'
fresh; L 'install_wrapper' >/dev/null 2>&1; command rm -f "$T/kvm"
FAIL_REMOVE=1 L 'uninstall' >/dev/null 2>&1; rc=$?
chk "C2d wrapper already missing + remove failure: no crash beyond rc!=0" '[[ $rc -ne 0 ]]'

